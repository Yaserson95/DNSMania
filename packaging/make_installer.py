# -*- coding: utf-8 -*-
"""
Собирает MSI-установщик DNS Mania (WiX Toolset v3).

Шаги:
  1. Копирует DNSMania.exe и необходимые *.dll из build/ в dist/DNSMania/
  2. Генерирует packaging/files.wxs (компоненты с детерминированными GUID,
     чтобы обновление через MajorUpgrade проходило корректно)
  3. Генерирует License.rtf из packaging/license.txt
  4. Компилирует и линкует MSI: dist/DNS Mania 1.0.msi

Требуется WiX v3 (candle.exe / light.exe) — по умолчанию D:\tools\wix314
(можно переопределить переменной окружения WIX).

Запуск:  python packaging/make_installer.py
"""
import os
import shutil
import subprocess
import sys
import uuid
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "build")
DIST = os.path.join(ROOT, "dist")
STAGE = os.path.join(DIST, "DNSMania")
PKG = os.path.dirname(os.path.abspath(__file__))
WIX_DIR = os.environ.get("WIX", r"D:\tools\wix314")
QT_BIN = os.environ.get("QT_BIN", r"D:\Qt\6.10.3\mingw_64\bin")
MSI_NAME = "DNS Mania 1.0.msi"

# Фиксированный namespace -> GUID компонентов стабильны между сборками.
GUID_NS = uuid.UUID("8e1c6a44-0b3f-4a45-9d0d-2b3a7c11eeee")


def component_guid(rel):
    return "{" + str(uuid.uuid5(GUID_NS, "DNSMania/" + rel.replace("\\", "/"))).upper() + "}"


def sanitize(rel, prefix):
    s = "".join(ch if ch.isalnum() else "_" for ch in rel)
    if not s or not s[0].isalpha():
        s = "x" + s
    return prefix + s


def stage():
    """Копирует exe в dist/DNSMania и разворачивает Qt-зависимости windeployqt
    (включая подкаталоги platforms/, imageformats/, styles/ и т.д. — именно
    там лежат платформенные плагины без которых приложение не стартует)."""
    if not os.path.isdir(BUILD):
        sys.exit("Каталог build/ не найден — сначала соберите проект (cmake --build build).")
    if os.path.isdir(STAGE):
        shutil.rmtree(STAGE)
    os.makedirs(STAGE)
    exe_src = os.path.join(BUILD, "DNSMania.exe")
    if not os.path.isfile(exe_src):
        sys.exit("DNSMania.exe не найден в build/ — сначала соберите проект.")
    shutil.copy2(exe_src, os.path.join(STAGE, "DNSMania.exe"))

    windeployqt = os.path.join(QT_BIN, "windeployqt.exe")
    if not os.path.exists(windeployqt):
        sys.exit("windeployqt не найден: %s (задайте переменную QT_BIN)." % windeployqt)
    run([windeployqt, "--no-translations",
         os.path.join(STAGE, "DNSMania.exe")], cwd=STAGE)

    staged = []
    for dirpath, _dirnames, filenames in os.walk(STAGE):
        rel_dir = os.path.relpath(dirpath, STAGE)
        for fn in sorted(filenames):
            staged.append(fn if rel_dir == "." else os.path.join(rel_dir, fn))
    return staged


def gen_files_wxs():
    """Генерирует files.wxs: компонент на каждый файл, детерминированные GUID."""
    root = {}
    for dirpath, _dirnames, filenames in os.walk(STAGE):
        rel_dir = os.path.relpath(dirpath, STAGE)
        prefix = [] if rel_dir == "." else rel_dir.split(os.sep)
        node = root
        for part in prefix:
            node = node.setdefault(part, {})
        for fn in sorted(filenames):
            node[fn] = "FILE"

    body = []
    refs = []

    def emit(node, prefix, indent):
        pad = "  " * indent
        for name in sorted(k for k, v in node.items() if v == "FILE"):
            rel = "/".join(prefix + [name])
            abs_src = os.path.join(STAGE, *rel.split("/"))
            cid = sanitize(rel, "cmp_")
            fid = sanitize(rel, "fil_")
            body.append('%s<Component Id="%s" Guid="%s">' % (pad, cid, component_guid(rel)))
            body.append('%s  <File Id="%s" Source="%s" KeyPath="yes" />' % (pad, fid, abs_src))
            body.append("%s</Component>" % pad)
            refs.append(cid)
        for name in sorted(k for k, v in node.items() if v != "FILE"):
            did = sanitize("/".join(prefix + [name]), "dir_")
            body.append('%s<Directory Id="%s" Name="%s">' % (pad, did, name))
            emit(node[name], prefix + [name], indent + 1)
            body.append("%s</Directory>" % pad)

    emit(root, [], 4)

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by make_installer.py; do not edit by hand. -->",
        '<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">',
        "  <Fragment>",
        '    <DirectoryRef Id="INSTALLFOLDER">',
    ] + body + [
        "    </DirectoryRef>",
        '    <ComponentGroup Id="AppFiles">',
    ] + ['      <ComponentRef Id="%s" />' % cid for cid in refs] + [
        "    </ComponentGroup>",
        "  </Fragment>",
        "</Wix>",
    ]
    out = os.path.join(PKG, "files.wxs")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return out, len(refs)


def rtf_escape(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch in "\\{}":
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\par\n")
        elif code < 128:
            out.append(ch)
        elif code < 32768:
            out.append("\\u%d?" % code)
        else:
            out.append("\\u%d?" % (code - 65536))
    return "".join(out)


def gen_license_rtf():
    """RTF из license.txt для диалога лицензии установщика."""
    txt_path = os.path.join(PKG, "license.txt")
    with open(txt_path, "r", encoding="utf-8") as f:
        text = f.read().strip()
    rtf = (
        r"{\rtf1\ansi\ansicpg1251\deff0"
        r"{\fonttbl{\f0\fswiss Segoe UI;}}"
        r"\viewkind4\uc1\pard\f0\fs18 "
        + rtf_escape(text)
        + "\n}"
    )
    out = os.path.join(PKG, "License.rtf")
    with open(out, "w", encoding="ascii", errors="strict") as f:
        f.write(rtf)
    return out


def run(cmd, cwd):
    print("  $ " + " ".join(cmd))
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, errors="replace")
    if res.stdout.strip():
        print(res.stdout.strip())
    if res.stderr.strip():
        print(res.stderr.strip())
    if res.returncode != 0:
        sys.exit("Команда завершилась с ошибкой (код %d)." % res.returncode)


def main():
    candle = os.path.join(WIX_DIR, "candle.exe")
    light = os.path.join(WIX_DIR, "light.exe")
    for tool in (candle, light):
        if not os.path.exists(tool):
            sys.exit("WiX не найден: %s (задайте переменную WIX)." % tool)

    print("[1/4] Копирование файлов в dist/DNSMania ...")
    copied = stage()
    print("      %d файлов: %s" % (len(copied), ", ".join(copied)))

    print("[2/4] Генерация files.wxs ...")
    wxs_path, ncomp = gen_files_wxs()
    print("      %s (%d компонентов)" % (wxs_path, ncomp))

    print("[3/4] Генерация License.rtf ...")
    rtf_path = gen_license_rtf()
    print("      %s" % rtf_path)

    print("[4/4] Компиляция MSI (candle + light) ...")
    obj_dir = os.path.join(PKG, "obj")
    os.makedirs(obj_dir, exist_ok=True)
    for src, obj in (("Product.wxs", "Product.wixobj"), ("files.wxs", "files.wixobj")):
        run([candle, "-nologo", "-arch", "x64",
             "-out", os.path.join(obj_dir, obj), src], cwd=PKG)
    msi_path = os.path.join(DIST, MSI_NAME)
    run([light, "-nologo", "-ext", "WixUIExtension",
         "-cultures:en-us", "-loc", "en-us.wxl",
         "-out", msi_path,
         os.path.join(obj_dir, "Product.wixobj"),
         os.path.join(obj_dir, "files.wixobj")], cwd=PKG)

    size_mb = os.path.getsize(msi_path) / (1024.0 * 1024.0)
    print("\nГотово: %s (%.2f МБ)" % (msi_path, size_mb))


if __name__ == "__main__":
    main()
